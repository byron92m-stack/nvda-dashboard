# Longest Spanish phrases must win over generic words. Sorting once at import
# time makes the mapping order-insensitive and prevents partial replacements
# such as "Caja neta (caja + inversiones - deuda)" -> "Net cash (caja...)".
_SORTED_TRANSLATIONS = sorted(TRANSLATIONS, key=lambda item: len(item[0]), reverse=True)


def translate(text: str) -> str:
    for spanish, english in _SORTED_TRANSLATIONS:
        text = text.replace(spanish, english)
    return text


def translate_obj(value):
    """Recursively translate strings in a Plotly figure dict.

    Plotly's to_json() escapes non-ASCII characters (\\u00f3), so translating
    the raw JSON would miss accented labels. Decoding to a dict first keeps
    the strings as Unicode and lets the mapping match them.
    """
    if isinstance(value, str):
        return translate(value)
    if isinstance(value, dict):
        return {key: translate_obj(val) for key, val in value.items()}
    if isinstance(value, (list, tuple)):
        return [translate_obj(val) for val in value]
    return value
